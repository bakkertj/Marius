//! Provenance of generated content, and the inference audit trail.
//!
//! Requirements: AI-011 (visible provenance and citations), AI-013, AI-015
//! (track model, provider, task, timestamp, cost), SEC-006 (log model use and
//! consequential automatic metadata changes), UI-010, AC-010, integrity rules
//! 5 and 6.

use serde::{Deserialize, Serialize};
use time::OffsetDateTime;

use crate::ids::{ChunkId, DocumentId, GlobalDocumentId, InferenceId, RevisionId};
use crate::policy::{InferenceTask, Locality, Sensitivity};

/// One source a generated note drew on.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Citation {
    pub document: GlobalDocumentId,
    /// The exact passage, when retrieval was chunk-level (SRCH-008).
    pub chunk: Option<ChunkId>,
    /// Label to display, e.g. `Alexandria › Construction`.
    pub label: String,
    /// Byte range within the source document, for click-to-highlight.
    pub byte_range: Option<(usize, usize)>,
}

/// How a generated note relates to the content it came from.
///
/// Stored alongside the note so the UI can always say what produced it, even
/// after the model configuration has changed (integrity rule 5).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct GeneratedNoteProvenance {
    /// The derived document this describes.
    pub document: DocumentId,
    /// The revision of that document this generation produced. A later
    /// regeneration adds a new revision rather than replacing this one
    /// (AI-013, AC-010).
    pub revision: RevisionId,
    pub inference: InferenceId,
    pub task: InferenceTask,
    pub provider: String,
    pub model: String,
    /// Identifier of the prompt template used, so a note can be regenerated
    /// the same way later (AI-016).
    pub prompt_id: Option<String>,
    pub sources: Vec<Citation>,
    #[serde(with = "time::serde::rfc3339")]
    pub generated_at: OffsetDateTime,
    /// True once a person has edited the note's body. Regeneration must then
    /// refuse to overwrite it and write a separate note or revision instead
    /// (AI-013, AC-010, integrity rule 6).
    pub user_edited: bool,
}

impl GeneratedNoteProvenance {
    /// Whether `regenerate` may replace the note's body in place.
    ///
    /// The whole of integrity rule 6 reduces to this: once a person has touched
    /// a generated note, the model gets a new revision, never the user's bytes.
    pub fn allows_in_place_regeneration(&self) -> bool {
        !self.user_edited
    }

    /// Short attribution line for the UI banner (UI-010).
    pub fn attribution(&self) -> String {
        format!(
            "Generated by {}/{} on {}",
            self.provider,
            self.model,
            self.generated_at.date()
        )
    }
}

/// Outcome of a policy decision about one inference request.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum InferenceOutcome {
    /// Ran, and the response was used.
    Completed,
    /// Refused by the policy engine before any content left the process
    /// (AI-008, AC-016).
    DeniedByPolicy,
    /// No eligible provider was reachable. Core features stay usable (AI-004).
    NoEligibleProvider,
    /// The provider was eligible but failed.
    ProviderError,
    /// Cancelled by the user.
    Cancelled,
}

impl InferenceOutcome {
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Completed => "completed",
            Self::DeniedByPolicy => "denied_by_policy",
            Self::NoEligibleProvider => "no_eligible_provider",
            Self::ProviderError => "provider_error",
            Self::Cancelled => "cancelled",
        }
    }

    /// True when document content actually left this process.
    pub const fn content_was_sent(self) -> bool {
        matches!(self, Self::Completed | Self::ProviderError)
    }

    pub const ALL: [InferenceOutcome; 5] = [
        Self::Completed,
        Self::DeniedByPolicy,
        Self::NoEligibleProvider,
        Self::ProviderError,
        Self::Cancelled,
    ];
}

impl std::fmt::Display for InferenceOutcome {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(self.as_str())
    }
}

impl std::str::FromStr for InferenceOutcome {
    type Err = UnknownInferenceOutcome;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        match s {
            "completed" => Ok(Self::Completed),
            "denied_by_policy" => Ok(Self::DeniedByPolicy),
            "no_eligible_provider" => Ok(Self::NoEligibleProvider),
            "provider_error" => Ok(Self::ProviderError),
            "cancelled" => Ok(Self::Cancelled),
            other => Err(UnknownInferenceOutcome(other.to_owned())),
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
#[error("unknown inference outcome {0:?}")]
pub struct UnknownInferenceOutcome(pub String);

/// One row of the inference audit log.
///
/// Written for *every* request the policy engine considers, including the ones
/// it refuses — a denial is the most important thing to be able to show a user
/// who asks whether their confidential vault stayed on the device (SEC-006,
/// AC-016).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct InferenceRecord {
    pub id: InferenceId,
    pub task: InferenceTask,
    /// Provider that was selected, or `None` when nothing was eligible.
    pub provider: Option<String>,
    pub model: Option<String>,
    pub locality: Option<Locality>,
    /// The effective sensitivity of the material in the request — the strictest
    /// level across every source document (AI-008).
    pub sensitivity: Sensitivity,
    /// Documents whose content was part of the request.
    pub documents: Vec<GlobalDocumentId>,
    pub outcome: InferenceOutcome,
    /// Why, in the engine's own words. Shown verbatim in the audit view.
    pub reason: String,
    pub prompt_tokens: Option<u32>,
    pub completion_tokens: Option<u32>,
    /// Cost in the provider's billing currency, when known (AI-015).
    pub cost: Option<f64>,
    pub currency: Option<String>,
    #[serde(with = "time::serde::rfc3339")]
    pub started_at: OffsetDateTime,
    pub duration_ms: Option<u64>,
}

impl InferenceRecord {
    /// A record for a request the policy engine refused. Deliberately
    /// constructible without a provider, since there was none.
    pub fn denied(
        task: InferenceTask,
        sensitivity: Sensitivity,
        documents: Vec<GlobalDocumentId>,
        reason: impl Into<String>,
    ) -> Self {
        Self {
            id: InferenceId::new(),
            task,
            provider: None,
            model: None,
            locality: None,
            sensitivity,
            documents,
            outcome: InferenceOutcome::DeniedByPolicy,
            reason: reason.into(),
            prompt_tokens: None,
            completion_tokens: None,
            cost: None,
            currency: None,
            started_at: OffsetDateTime::now_utc(),
            duration_ms: None,
        }
    }

    /// True when this row records content leaving the device.
    pub fn left_the_device(&self) -> bool {
        self.outcome.content_was_sent()
            && matches!(self.locality, Some(Locality::SelfHosted | Locality::Remote))
    }
}

/// How certain a grounded answer is about a claim.
///
/// Requirements: SRCH-012 (clearly distinguish supported source claims from
/// generated inference or uncertainty), AC-008.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ClaimSupport {
    /// Directly stated by a cited passage.
    Supported,
    /// The model's synthesis across passages; plausible but not stated.
    Inferred,
    /// The sources do not settle it. Surfaced rather than hidden.
    Unsupported,
}

impl ClaimSupport {
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Supported => "supported",
            Self::Inferred => "inferred",
            Self::Unsupported => "unsupported",
        }
    }

    /// Marker the UI and CLI prefix a claim with.
    pub const fn marker(self) -> &'static str {
        match self {
            Self::Supported => "✓",
            Self::Inferred => "≈",
            Self::Unsupported => "?",
        }
    }

    pub const ALL: [ClaimSupport; 3] = [Self::Supported, Self::Inferred, Self::Unsupported];
}

impl std::fmt::Display for ClaimSupport {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(self.as_str())
    }
}

/// One statement in a grounded answer, with its support.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Claim {
    pub text: String,
    pub support: ClaimSupport,
    /// Citations backing the claim. Required to be non-empty for
    /// [`ClaimSupport::Supported`] — see [`Claim::is_well_formed`].
    pub citations: Vec<Citation>,
}

impl Claim {
    /// True when the claim's support level matches its evidence.
    ///
    /// A "supported" claim with no citation is exactly the failure mode
    /// SRCH-012 exists to prevent, so answers are validated before display.
    pub fn is_well_formed(&self) -> bool {
        match self.support {
            ClaimSupport::Supported => !self.citations.is_empty(),
            ClaimSupport::Inferred | ClaimSupport::Unsupported => true,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ids::VaultId;

    fn global() -> GlobalDocumentId {
        GlobalDocumentId::new(VaultId::new(), DocumentId::new())
    }

    fn provenance(user_edited: bool) -> GeneratedNoteProvenance {
        GeneratedNoteProvenance {
            document: DocumentId::new(),
            revision: RevisionId::new(),
            inference: InferenceId::new(),
            task: InferenceTask::Summarization,
            provider: "ollama".into(),
            model: "llama3.2".into(),
            prompt_id: Some("summary.v1".into()),
            sources: vec![Citation {
                document: global(),
                chunk: None,
                label: "Alexandria".into(),
                byte_range: Some((0, 120)),
            }],
            generated_at: OffsetDateTime::now_utc(),
            user_edited,
        }
    }

    #[test]
    fn a_user_edited_note_is_never_regenerated_in_place() {
        // AC-010, AI-013, integrity rule 6.
        assert!(provenance(false).allows_in_place_regeneration());
        assert!(!provenance(true).allows_in_place_regeneration());
    }

    #[test]
    fn generated_notes_keep_their_sources() {
        // Integrity rule 5.
        let p = provenance(false);
        assert!(!p.sources.is_empty());
        assert!(p.attribution().contains("ollama/llama3.2"));
    }

    #[test]
    fn a_denied_request_is_auditable_without_a_provider() {
        // SEC-006 and AC-016: the denial itself is the evidence.
        let record = InferenceRecord::denied(
            InferenceTask::Tagging,
            Sensitivity::Confidential,
            vec![global()],
            "vault is local-only",
        );
        assert_eq!(record.outcome, InferenceOutcome::DeniedByPolicy);
        assert!(!record.outcome.content_was_sent());
        assert!(!record.left_the_device());
        assert_eq!(record.provider, None);
        assert!(record.reason.contains("local-only"));
    }

    #[test]
    fn a_failed_remote_call_still_counts_as_content_having_left() {
        // The request body was already on the wire; the audit must say so.
        let mut record = InferenceRecord::denied(
            InferenceTask::Summarization,
            Sensitivity::Unrestricted,
            vec![global()],
            "upstream 500",
        );
        record.outcome = InferenceOutcome::ProviderError;
        record.locality = Some(Locality::Remote);
        record.provider = Some("openrouter".into());
        assert!(record.left_the_device());
    }

    #[test]
    fn local_completion_does_not_count_as_leaving_the_device() {
        let mut record = InferenceRecord::denied(
            InferenceTask::Embedding,
            Sensitivity::Confidential,
            vec![global()],
            "ok",
        );
        record.outcome = InferenceOutcome::Completed;
        record.locality = Some(Locality::Local);
        assert!(!record.left_the_device());
    }

    #[test]
    fn a_supported_claim_must_cite_something() {
        // SRCH-012.
        let unsupported_but_asserted = Claim {
            text: "The Pharos stood 100 metres tall.".into(),
            support: ClaimSupport::Supported,
            citations: Vec::new(),
        };
        assert!(!unsupported_but_asserted.is_well_formed());

        let honest = Claim {
            text: "The Pharos stood 100 metres tall.".into(),
            support: ClaimSupport::Inferred,
            citations: Vec::new(),
        };
        assert!(honest.is_well_formed());
    }

    #[test]
    fn support_levels_have_distinct_markers() {
        let markers: Vec<_> = ClaimSupport::ALL.iter().map(|s| s.marker()).collect();
        assert_eq!(markers.len(), 3);
        assert_eq!(
            markers
                .iter()
                .collect::<std::collections::BTreeSet<_>>()
                .len(),
            3
        );
    }

    #[test]
    fn outcome_tokens_round_trip() {
        for o in InferenceOutcome::ALL {
            assert_eq!(o, o.as_str().parse().unwrap());
        }
    }
}
